"""Source-backed objective exclusions shared by legal search and P2.

Only a fully described, single-effect source rank may be excluded. The
selected solo IR must prove that the excluded mechanic has no competitor;
unsupported/unknown source effects remain blocked.
"""
from __future__ import annotations

import re


def solo_threat_exclusion(ir, rank):
    """Return checked DOES_NOT_AFFECT_SIM evidence, or None (fail closed).

    Threat reduction cannot change enemy target choice in the selected
    single-player, single-target solo executor with no allied actor/pet.
    This is NOT a claim that threat has no effect in group or pet scenarios.
    """
    provenance = rank.provenance or {}
    source = provenance.get("source") or {}
    tooltip = provenance.get("raw_tooltip")
    if not isinstance(source, dict) or not isinstance(tooltip, str):
        return None
    if (not str(source.get("url", "")).startswith("https://")
            or not source.get("capture_id")):
        return None
    match = re.fullmatch(
        r"Reduces the threat generated by your Nature and Arcane spells by "
        r"(\d+(?:\.\d+)?)%\.", tooltip.strip(), flags=re.IGNORECASE)
    if not match or not 0. < float(match.group(1)) <= 100.:
        return None
    if (ir.actor.actor_type != "player" or ir.companions
            or ir.timed_summons or ir.actor_links):
        return None
    if any(action.owner_actor_id != ir.actor.id for action in ir.actions):
        return None
    if any(attack.target_actor_id != ir.actor.id
           for attack in ir.incoming_attacks):
        return None
    return {
        "status": "DOES_NOT_AFFECT_SIM",
        "source_url": source["url"],
        "source_capture_id": source["capture_id"],
        "source_effect": "nature_arcane_threat_reduction",
        "source_rank_percent": float(match.group(1)),
        "scenario": "solo_single_player_no_companions_or_alternative_threat_targets",
        "checked": True,
    }
